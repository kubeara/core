function formatRevealedValue(variable: TemplateVariable, value: unknown): string {
  if (value === undefined || value === null || value === "") {
    return "—";
  }

  if (variable.type === "boolean") {
    return value ? "true" : "false";
  }

  return String(value);
}

function canRegenerateValue(variableName: string): boolean {
  return (
    isAutoGeneratedMagicVariable(variableName) ||
    isSensitiveVariable(variableName)
  );
}

function regenerateValue(variableName: string): string {
  const command = parseMagicEnvCommand(variableName);
  if (command) {
    return generateMagicEnvValue(command);
  }
  return generateMagicEnvValue("PASSWORD");
}

function TextVariableInput({
  variable,
  value,
  onChange,
  "aria-invalid": ariaInvalid,
}: {
  variable: TemplateVariable;
  value: unknown;
  onChange: (value: string | number | undefined) => void;
  "aria-invalid"?: boolean;
}) {
  return (
    <Input
      type={variable.type === "number" ? "number" : "text"}
      value={value === undefined || value === null ? "" : String(value)}
      autoComplete="off"
      aria-invalid={ariaInvalid}
      className={ariaInvalid ? "deploy-var-input--error" : undefined}
      onChange={(event) => {
        if (variable.type === "number") {
          const raw = event.target.value;
          if (raw === "") {
            // Use empty string — react-hook-form treats `undefined` as "revert to default".
            onChange("");
            return;
          }
          const parsed = Number(raw);
          onChange(Number.isNaN(parsed) ? "" : parsed);
          return;
        }
        onChange(event.target.value);
      }}
    />
  );
}

function VariableRow<TFieldValues extends FieldValues>({
  control,
  variable,
  isEditing,
  isRequired,
}: {
  control: Control<TFieldValues>;
  variable: TemplateVariable;
  isEditing: boolean;
  isRequired: boolean;
}) {
  const [revealed, setRevealed] = useState(false);
  const showRegenerate = isEditing && canRegenerateValue(variable.name);

  useEffect(() => {
    setRevealed(false);
  }, [isEditing]);

  return (
    <FormField
      control={control}
      name={variable.name as never}
      render={({ field, fieldState }) => (
        <FormItem
          className={`deploy-var-row${fieldState.error ? " deploy-var-row--error" : ""}`}
        >
          <span className="deploy-var-name">
            {variable.name}
            {isRequired ? (
              <span className="form-field-required" aria-hidden="true">
                {" "}
                *
              </span>
            ) : null}
          </span>

          <div className="deploy-var-value-cell">
            {isEditing ? (
              <FormControl>
                {variable.type === "boolean" ? (
                  <div className="deploy-var-boolean-edit">
                    <span className="deploy-var-boolean-label">
                      {field.value ? "Enabled" : "Disabled"}
                    </span>
                    <Switch
                      checked={Boolean(field.value)}
                      onCheckedChange={field.onChange}
                    />
                  </div>
                ) : (
                  <TextVariableInput
                    variable={variable}
                    value={field.value}
                    onChange={field.onChange}
                    aria-invalid={fieldState.error ? true : undefined}
                  />
                )}
              </FormControl>
            ) : (
              <span className="deploy-var-value">
                {revealed
                  ? formatRevealedValue(variable, field.value)
                  : MASKED_VALUE}
              </span>
            )}

            {!isEditing ? (
              <button
                type="button"
                className="deploy-var-action-btn"
                onClick={() => setRevealed((value) => !value)}
                aria-label={revealed ? "Hide value" : "Show value"}
                aria-pressed={revealed}
              >
                {revealed ? <EyeOffIcon /> : <EyeIcon />}
              </button>
            ) : showRegenerate ? (
              <TooltipHint content="Regenerate value">
                <button
                  type="button"
                  className="deploy-var-action-btn"
                  onClick={() => field.onChange(regenerateValue(variable.name))}
                  aria-label={`Regenerate ${variable.name}`}
                >
                  <RegenerateIcon />
                </button>
              </TooltipHint>
            ) : (
              <span className="deploy-var-action-spacer" aria-hidden />
            )}
          </div>

          <FormMessage className="form-field-error deploy-var-error" role="alert" />
        </FormItem>
      )}
    />
  );
}

function VariableList<TFieldValues extends FieldValues>({
  control,
  variables,
  isEditing,
  isRequired,
}: {
  control: Control<TFieldValues>;
  variables: TemplateVariable[];
  isEditing: boolean;
  isRequired: boolean;
}) {
  if (variables.length === 0) return null;

  return (
    <div className="deploy-var-list">
      {variables.map((variable) => (
        <VariableRow
          key={variable.name}
          control={control}
          variable={variable}
          isEditing={isEditing}
          isRequired={isRequired}
        />
      ))}
    </div>
  );
}

export function DynamicDeployFields<TFieldValues extends FieldValues>({
  control,
  variables,
  isEditing,
}: DynamicDeployFieldsProps<TFieldValues>) {
  const [advancedOpen, setAdvancedOpen] = useState(false);

  if (variables.length === 0) {
    return (
      <p className="deploy-form-empty-state">
        No configuration required for this template. Platform defaults will be
        applied automatically when you deploy.
      </p>
    );
  }

  const { ports, required, optional } = groupTemplateVariables(variables);
  const requiredVariables = [...ports, ...required];

  return (
    <div className="deploy-vars-panel">
      <section className="deploy-vars-section">
        <header className="deploy-vars-section-header">
          <h2>Required variables</h2>
          <p>Configuration values needed before deployment can proceed.</p>
        </header>
        <VariableList
          control={control}
          variables={requiredVariables}
          isEditing={isEditing}
          isRequired
        />
      </section>

      {optional.length > 0 && (
        <section className="deploy-vars-section deploy-vars-advanced-section">
          <button
            type="button"
            className="deploy-vars-advanced-toggle"
            onClick={() => setAdvancedOpen((open) => !open)}
            aria-expanded={advancedOpen}
          >
            <span>Advanced Options</span>
            <svg
              className={`deploy-vars-advanced-chevron${advancedOpen ? " is-open" : ""}`}
              width="16"
              height="16"
              viewBox="0 0 24 24"
              fill="none"
              aria-hidden
            >
              <path
                d="M6 9l6 6 6-6"
                stroke="currentColor"
                strokeWidth="2"
                strokeLinecap="round"
                strokeLinejoin="round"
              />
            </svg>
          </button>

          {advancedOpen ? (
            <VariableList
              control={control}
              variables={optional}
              isEditing={isEditing}
              isRequired={false}
            />
          ) : null}
        </section>
      )}
    </div>
  );
}
