import { groupTemplateVariables, isSensitiveVariable } from "../utils/field-utils";
import {
  generateMagicEnvValue,
  isAutoGeneratedMagicVariable,
  parseMagicEnvCommand,
} from "../utils/service-magic-env";

const MASKED_VALUE = "************";

type DynamicDeployFieldsProps<TFieldValues extends FieldValues> = {
  control: Control<TFieldValues>;
  variables: TemplateVariable[];
  isEditing: boolean;
};

